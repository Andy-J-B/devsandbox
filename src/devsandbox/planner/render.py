"""Human-readable plan rendering for the API, CLI, and approval UX."""

from __future__ import annotations

import json

from .models import Plan, ProposedPlan, TaskDraft


def render_dependency_graph(tasks: list[TaskDraft]) -> str:
    """Render the task graph as an ASCII forest."""
    tasks_by_key = {task.key: task for task in tasks}
    if not tasks_by_key:
        return "(empty plan)"

    children: dict[str, list[str]] = {key: [] for key in tasks_by_key}
    for task in tasks_by_key.values():
        for dependency in task.depends_on:
            if dependency in tasks_by_key and dependency != task.key:
                children[dependency].append(task.key)
    for values in children.values():
        values.sort(key=list(tasks_by_key).index)

    roots = [
        key
        for key, task in tasks_by_key.items()
        if not any(dep in tasks_by_key and dep != key for dep in task.depends_on)
    ]
    if not roots:
        roots = list(tasks_by_key)

    lines: list[str] = []
    seen: set[str] = set()

    def render(key: str, prefix: str, connector: str) -> None:
        label = key if key not in seen else f"{key} (see above)"
        lines.append(f"{prefix}{connector}{label}")
        if key in seen:
            return
        seen.add(key)
        kids = children.get(key, [])
        for position, child in enumerate(kids):
            last = position == len(kids) - 1
            child_connector = "└── " if last else "├── "
            child_prefix = prefix + ("    " if connector in {"", "└── "} else "│   ")
            render(child, child_prefix, child_connector)

    for root in roots:
        render(root, "", "")
    return "\n".join(lines)


def _plan_header(plan: Plan | ProposedPlan) -> str:
    if isinstance(plan, Plan):
        return f"# Plan v{plan.version} ({plan.status.value})"
    return "# Proposed plan"


def render_plan_markdown(plan: Plan | ProposedPlan) -> str:
    """Render a plan as Markdown with graph, criteria, checks, and warnings."""
    lines: list[str] = [_plan_header(plan), ""]
    if isinstance(plan, Plan):
        lines.extend(
            [
                f"- **Project:** `{plan.project_id}`",
                f"- **Plan id:** `{plan.id}`",
                f"- **Generated by:** `{plan.generated_by or 'unknown'}`",
                f"- **Planner version:** `{plan.planner_version or 'unknown'}`",
                f"- **Source revision:** `{plan.source_revision or 'unknown'}`",
            ]
        )
        if plan.approved_by:
            lines.append(f"- **Approved by:** `{plan.approved_by}`")
        lines.append("")
    if plan.rationale:
        lines.extend(["## Rationale", "", plan.rationale, ""])
    if plan.assumptions:
        lines.extend(["## Assumptions", "", *[f"- {item}" for item in plan.assumptions], ""])
    if plan.risks:
        lines.extend(["## Risks", "", *[f"- {item}" for item in plan.risks], ""])

    lines.extend(
        ["## Dependency graph", "", "```text", render_dependency_graph(plan.tasks), "```", ""]
    )
    lines.extend(["## Tasks", ""])
    for index, task in enumerate(plan.tasks, start=1):
        lines.append(f"### {index}. `{task.key}` — {task.title}")
        lines.append("")
        if task.depends_on:
            lines.append("- **Depends on:** " + ", ".join(f"`{dep}`" for dep in task.depends_on))
        else:
            lines.append("- **Depends on:** _(none)_")
        lines.append(f"- **Priority:** {task.priority}")
        lines.append(f"- **Timeout:** {task.timeout_seconds}s")
        lines.append(f"- **Max retries:** {task.max_retries}")
        resources = task.resources
        lines.append(
            "- **Resources:** "
            f"{resources.cpu_cores} CPU, {resources.memory_mb} MB RAM, "
            f"{resources.disk_mb} MB disk, {resources.pids_limit} pids"
        )
        lines.append("")
        lines.append("**Success criteria**")
        lines.extend([f"- {criterion}" for criterion in task.success_criteria] or ["- _(none)_"])
        lines.append("")
        lines.append("**Checks**")
        if task.checks:
            for check in task.checks:
                requirement = "required" if check.required else "optional"
                lines.append(
                    f"- [{requirement}] `{check.name}`: `{check.run}` ({check.timeout_seconds}s)"
                )
        else:
            lines.append("- _(none)_")
        lines.append("")
        if task.expected_files:
            lines.append(
                "- **Expected files:** " + ", ".join(f"`{p}`" for p in task.expected_files)
            )
        if task.restricted_files:
            lines.append(
                "- **Restricted files:** " + ", ".join(f"`{p}`" for p in task.restricted_files)
            )
        if task.description:
            lines.extend(["", task.description])
        if task.instructions:
            lines.extend(["", "**Instructions**", "", task.instructions])
        lines.append("")

    issues = plan.issues if isinstance(plan, Plan) else []
    if issues:
        lines.extend(["## Validation issues", ""])
        for issue in issues:
            location = f" `{issue.task_key}`" if issue.task_key else ""
            lines.append(f"- **{issue.severity.value}**{location} [{issue.code}]: {issue.issue}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_plan_json(plan: Plan | ProposedPlan) -> str:
    """Render a plan as stable, pretty JSON."""
    return json.dumps(plan.model_dump(mode="json"), indent=2, sort_keys=True)


__all__ = ["render_dependency_graph", "render_plan_json", "render_plan_markdown"]
