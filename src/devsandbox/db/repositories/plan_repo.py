"""Plan repository."""

from __future__ import annotations

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from ..models import PlanModel


class PlanRepo:
    """Repository for plan records."""

    def __init__(self, session: AsyncSession) -> None:
        self.session = session

    async def get(self, plan_id: str) -> PlanModel | None:
        """Return the plan or ``None``."""
        result = await self.session.execute(select(PlanModel).where(PlanModel.id == plan_id))
        return result.scalar_one_or_none()

    async def get_active_for_project(self, project_id: str) -> PlanModel | None:
        """Return the active plan for a project, if any."""
        result = await self.session.execute(
            select(PlanModel).where(
                PlanModel.project_id == project_id, PlanModel.status == "active"
            )
        )
        return result.scalar_one_or_none()

    async def create(self, plan: PlanModel) -> PlanModel:
        """Persist a new plan."""
        self.session.add(plan)
        await self.session.flush()
        return plan

    async def list_for_project(self, project_id: str, limit: int = 100) -> list[PlanModel]:
        """Return plans for a project, newest version first."""
        result = await self.session.execute(
            select(PlanModel)
            .where(PlanModel.project_id == project_id)
            .order_by(PlanModel.version.desc())
            .limit(limit)
        )
        return list(result.scalars().all())

    async def latest_for_project(self, project_id: str) -> PlanModel | None:
        """Return the newest plan for a project, if any."""
        result = await self.session.execute(
            select(PlanModel)
            .where(PlanModel.project_id == project_id)
            .order_by(PlanModel.version.desc())
            .limit(1)
        )
        return result.scalar_one_or_none()

    async def next_version(self, project_id: str) -> int:
        """Return the next plan version number for a project."""
        result = await self.session.execute(
            select(func.max(PlanModel.version)).where(PlanModel.project_id == project_id)
        )
        current = result.scalar_one_or_none()
        return int(current or 0) + 1

    async def count_replans(self, project_id: str) -> int:
        """Return the number of plans generated by replanning."""
        result = await self.session.execute(
            select(func.count())
            .select_from(PlanModel)
            .where(PlanModel.project_id == project_id)
            .where(PlanModel.generated_by.like("replan:%"))
        )
        return int(result.scalar_one())
