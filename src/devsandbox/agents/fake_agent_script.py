"""Deterministic fake coding agent for E2E tests (no LLM required).

The script is self-contained and can be run three ways:

* ``python -m devsandbox.agents.fake_agent_script`` on the host,
* ``python path/to/fake_agent_script.py`` from a test image,
* ``python -c "$FAKE_AGENT_SOURCE" ...`` inside a sandbox by
  :class:`~devsandbox.agents.fake.FakeScriptAdapter`.

Modes cover the failure shapes the orchestrator must handle: normal
edit+commit, explicit failure, hang/timeout, no commit, restricted-path touch,
lying about success, and leaking a secret to stdout.
"""

from __future__ import annotations

import sys
from collections.abc import Callable
from typing import cast

FAKE_AGENT_SOURCE = r'''#!/usr/bin/env python3
"""Deterministic fake coding agent (generated by devsandbox)."""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path


def _git(workspace: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            "git",
            "-c",
            "user.name=DevSandbox Fake Agent",
            "-c",
            "user.email=fake-agent@devsandbox.local",
            *args,
        ],
        cwd=workspace,
        text=True,
        capture_output=True,
        check=False,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="DevSandbox deterministic fake agent")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--fail", action="store_true", help="exit 1 without changing files")
    modes.add_argument("--hang", action="store_true", help="sleep until the sandbox times out")
    modes.add_argument("--no-commit", action="store_true", help="edit but do not commit")
    modes.add_argument("--touch-restricted", action="store_true", help="edit a restricted path")
    modes.add_argument("--lie", action="store_true", help="claim success without any changes")
    modes.add_argument("--leak-secret", action="store_true", help="print a secret env value")
    parser.add_argument("--file", default="AGENT_OUTPUT.md", help="file to edit")
    parser.add_argument(
        "--secret-env", default="DEVSANDBOX_FAKE_SECRET", help="env var to leak"
    )
    parser.add_argument("--hang-seconds", type=float, default=3600.0)
    parser.add_argument("--content", default="", help="content to write")
    args = parser.parse_args(argv)

    workspace = Path(os.environ.get("DEVSANDBOX_WORKSPACE", os.getcwd()))

    if args.leak_secret:
        print("FAKE_AGENT_LEAK: " + os.environ.get(args.secret_env, ""))
        return 0

    if args.fail:
        print("FAKE_AGENT_FAILURE: requested failure", file=sys.stderr)
        return 1

    if args.hang:
        print("FAKE_AGENT_HANG: sleeping", flush=True)
        time.sleep(args.hang_seconds)
        return 0

    if args.lie:
        print("FAKE_AGENT_SUMMARY: all tests pass; task complete (no changes made)")
        return 0

    target = (
        Path(".github/workflows/devsandbox-fake.yml")
        if args.touch_restricted
        else Path(args.file)
    )
    target_path = workspace / target
    target_path.parent.mkdir(parents=True, exist_ok=True)
    content = args.content or (
        "Generated by the DevSandbox deterministic fake agent.\n"
        f"attempt={os.environ.get('DEVSANDBOX_ATTEMPT', 'unknown')}\n"
        f"task={os.environ.get('DEVSANDBOX_TASK', 'unknown')}\n"
    )
    target_path.write_text(content, encoding="utf-8")
    print(f"FAKE_AGENT_EDIT: wrote {target}")

    if args.no_commit:
        print("FAKE_AGENT_SUMMARY: edited without committing")
        return 0

    add = _git(workspace, "add", "--", str(target))
    if add.returncode != 0:
        print("FAKE_AGENT_ERROR: git add failed: " + add.stderr, file=sys.stderr)
        return 1
    commit = _git(workspace, "commit", "-m", f"fake agent: update {target}")
    if commit.returncode != 0:
        print("FAKE_AGENT_ERROR: git commit failed: " + commit.stderr, file=sys.stderr)
        return 1
    print(f"FAKE_AGENT_SUMMARY: committed {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def main(argv: list[str] | None = None) -> int:
    """Run the embedded fake agent script (host-side convenience entry point)."""
    namespace: dict[str, object] = {"__name__": "__devsandbox_fake_agent__"}
    exec(compile(FAKE_AGENT_SOURCE, "<devsandbox-fake-agent>", "exec"), namespace)
    run_main = cast(Callable[[list[str] | None], int], namespace["main"])
    return run_main(argv)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
